import type { NextConfig } from "next";

/**
 * Baseline security headers applied to every route (P1#11).
 * CSP is intentionally NOT set here — 12-language marketing pages with
 * inline OG/JSON-LD and Vercel Analytics make a correct CSP non-trivial;
 * tracked as a separate P2 backlog item.
 */
const SECURITY_HEADERS = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains",
  },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: SECURITY_HEADERS,
      },
    ];
  },
};

export default nextConfig;
